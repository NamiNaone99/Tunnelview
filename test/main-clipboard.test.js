'use strict';
/* node --test test/main-clipboard.test.js — clipboard.js "do not monitor" handling (fake clipboard). */
const test = require('node:test');
const assert = require('node:assert/strict');

const { ClipboardWatcher } = require('../src/main/clipboard');

function fakeClipboard(state) {
  return {
    async read() {
      return [{ types: ['text/plain'], getType: async () => new Blob([state.text], { type: 'text/plain' }) }];
    },
    async has(f) { return (state.raw || []).includes(f); },
    async writeText() {},
    async write() {},
  };
}

function watcher(state, deps) {
  // A fixed change counter: the real one (GetClipboardSequenceNumber) would make the tests depend on
  // whatever this machine's clipboard does meanwhile.
  const w = new ClipboardWatcher({ clipboard: fakeClipboard(state), platform: 'win32', readCount: () => 1, ...deps });
  const got = [];
  w.on('change', (item) => got.push(item.text));
  const tick = async () => { w._lastCount = -1; await w._tick(); }; // pretend the change counter moved
  return { w, got, tick };
}

const formats = (present, dword = null) => ({
  has: (name) => present.includes(name),
  readDword: () => dword,
});

test('ExcludeClipboardContentFromMonitorProcessing / Clipboard Viewer Ignore items are skipped, not retried', async () => {
  for (const marker of ['ExcludeClipboardContentFromMonitorProcessing', 'Clipboard Viewer Ignore']) {
    const state = { text: 'hunter2' };
    let present = [marker];
    const { w, got, tick } = watcher(state, { formats: { has: (n) => present.includes(n), readDword: () => null } });
    await tick();
    assert.deepEqual(got, [], `${marker}: not delivered`);
    assert.match(w._lastSig, /^x:/, 'signature advanced past the item');
    await tick();
    assert.deepEqual(got, [], 'still skipped on the next poll');
    // The next ordinary copy is delivered, even with the same text.
    present = [];
    await tick();
    assert.deepEqual(got, ['hunter2']);
  }
});

test('CanIncludeInClipboardHistory: DWORD 0 (or unreadable) → skipped, 1 → delivered', async () => {
  let r = watcher({ text: 'a' }, { formats: formats(['CanIncludeInClipboardHistory'], 0) });
  await r.tick();
  assert.deepEqual(r.got, []);
  r = watcher({ text: 'b' }, { formats: formats(['CanIncludeInClipboardHistory'], null) });
  await r.tick();
  assert.deepEqual(r.got, []);
  r = watcher({ text: 'c' }, { formats: formats(['CanIncludeInClipboardHistory'], 1) });
  await r.tick();
  assert.deepEqual(r.got, ['c']);
});

test('fallback without native access: Electron clipboard.has with the raw-format form or the bare name', async () => {
  let r = watcher({ text: 'p', raw: ['electron application/osclipboard;format="ExcludeClipboardContentFromMonitorProcessing"'] }, { formats: null });
  await r.tick();
  assert.deepEqual(r.got, []);
  r = watcher({ text: 'q', raw: ['Clipboard Viewer Ignore'] }, { formats: null });
  await r.tick();
  assert.deepEqual(r.got, []);
  r = watcher({ text: 'r', raw: [] }, { formats: null });
  await r.tick();
  assert.deepEqual(r.got, ['r']);
});

test('other platforms never consult Windows formats', async () => {
  const r = watcher({ text: 'mac' }, { platform: 'darwin', formats: formats(['ExcludeClipboardContentFromMonitorProcessing']) });
  await r.tick();
  assert.deepEqual(r.got, ['mac']);
});

/* ------------------------------------------------------------------ macOS nspasteboard markers */

test('macOS: org.nspasteboard Concealed / Transient / AutoGenerated items are not delivered', async () => {
  for (const uti of ['org.nspasteboard.ConcealedType', 'org.nspasteboard.TransientType', 'org.nspasteboard.AutoGeneratedType']) {
    const state = { text: 'hunter2-secret', raw: [`electron application/osclipboard;format="${uti}"`] };
    const { w, got, tick } = watcher(state, { platform: 'darwin' });
    await tick();
    assert.deepEqual(got, [], `${uti}: not delivered`);
    assert.match(w._lastSig, /^x:/, 'skipped, not retried');
    // An ordinary copy afterwards is delivered.
    state.raw = [];
    state.text = 'plain';
    await tick();
    assert.deepEqual(got, ['plain']);
  }
});

test('macOS: one failing has() probe does not hide the other markers', async () => {
  const state = { text: 's3cret' };
  const cb = fakeClipboard(state);
  cb.has = async (f) => {
    if (f.includes('ConcealedType')) throw new Error('unsupported');
    return f === 'electron application/osclipboard;format="org.nspasteboard.TransientType"';
  };
  const w = new ClipboardWatcher({ clipboard: cb, platform: 'darwin', readCount: () => 1 });
  const got = [];
  w.on('change', (item) => got.push(item.text));
  w._lastCount = -1;
  await w._tick();
  assert.deepEqual(got, []);
});

/* ------------------------------------------------------------------ probe + read atomicity */

test('a copy landing between the "do not monitor" probe and the read is dropped, then re-read', async () => {
  // t0: an ordinary item (probe says fine); during read() a password manager copies a marked secret.
  const state = { text: 'old', raw: [], count: 5 };
  const cb = fakeClipboard(state);
  const realRead = cb.read;
  let swapOnRead = true;
  cb.read = async () => {
    if (swapOnRead) {
      swapOnRead = false;
      state.text = 'p4ssw0rd';
      state.raw = ['ExcludeClipboardContentFromMonitorProcessing'];
      state.count = 6;
    }
    return realRead();
  };
  const w = new ClipboardWatcher({ clipboard: cb, platform: 'win32', formats: null, readCount: () => state.count });
  const got = [];
  w.on('change', (item) => got.push(item.text));
  w._lastCount = 4;
  await w._tick();
  assert.deepEqual(got, [], 'nothing delivered on the inconsistent tick');
  assert.equal(w._lastCount, 4, 'baseline kept, so the next tick re-reads');
  assert.equal(w._lastSig, null);
  await w._tick(); // counter stable at 6: the new item is classified as excluded
  assert.deepEqual(got, []);
  assert.equal(w._lastCount, 6);
  assert.match(w._lastSig, /^x:/);
  await w._tick();
  assert.deepEqual(got, [], 'not retried');
});

test('without a change counter the probe runs again after the read', async () => {
  const state = { text: 'old', raw: [] };
  const cb = fakeClipboard(state);
  const realRead = cb.read;
  cb.read = async () => {
    state.text = 'p4ssw0rd';
    state.raw = ['electron application/osclipboard;format="org.nspasteboard.ConcealedType"'];
    return realRead();
  };
  const w = new ClipboardWatcher({ clipboard: cb, platform: 'darwin', readCount: () => null });
  const got = [];
  w.on('change', (item) => got.push(item.text));
  await w._tick();
  assert.deepEqual(got, [], 'second probe saw the marker');
  // A stable ordinary item is still delivered.
  cb.read = realRead;
  state.raw = [];
  state.text = 'fine';
  await w._tick();
  assert.deepEqual(got, ['fine']);
});

test('an ordinary change with a stable counter is delivered once', async () => {
  const state = { text: 'hello', raw: [], count: 10 };
  const w = new ClipboardWatcher({ clipboard: fakeClipboard(state), platform: 'win32', formats: null, readCount: () => state.count });
  const got = [];
  w.on('change', (item) => got.push(item.text));
  w._lastCount = 9;
  await w._tick();
  await w._tick();
  assert.deepEqual(got, ['hello']);
  assert.equal(w._lastCount, 10);
});
