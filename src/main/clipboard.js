'use strict';
/*
 * Clipboard watcher + writer — docs/ARCHITECTURE.md §7 (clipboard.js).
 *
 *   const clipboardWatcher = require('./clipboard');
 *   clipboardWatcher.subscribe(webContents, { canReceive })   // 'clipboard:changed' delivery
 *   clipboardWatcher.unsubscribe(webContents)
 *   clipboardWatcher.start() / .stop()        // polling runs only while ≥ 1 subscriber (or explicit start)
 *   clipboardWatcher.on('change', {kind:'text', text} | {kind:'image', png:Buffer})
 *   await clipboardWatcher.write({kind:'text', text} | {kind:'image', png})   // echo-suppressed
 *
 * Electron 45 replaced the synchronous clipboard API with an async W3C-style one
 * (clipboard.read() → ClipboardItem[], item.getType(mime) → Blob, clipboard.write([ClipboardItem]),
 * clipboard.readText()/writeText()); this module uses that API exclusively.
 *
 * Change detection: require('./native/changecount').get() (Win: GetClipboardSequenceNumber,
 * mac: NSPasteboard.changeCount) is polled every 500 ms — a cheap integer compare. Only when it
 * moves is the clipboard actually read. Without the native counter we fall back to reading the
 * clipboard each tick and comparing a content signature.
 *
 * The "do not monitor" probe and the content read are two separate clipboard accesses, so a read
 * is bracketed by the change counter: when it moved in between (a password manager copied just
 * then), the result is dropped and the next tick reads the new item consistently. Without a
 * counter the probe runs again after the read, and the item is delivered only when both probes
 * say "not excluded".
 */
const { EventEmitter } = require('events');
const crypto = require('crypto');
const PROTOCOL = require('../shared/protocol');

const POLL_MS = 500;
const SUPPRESS_MS = 3000;
const PNG_MAGIC = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
const MAX_TEXT = PROTOCOL.CONTROL.MAX_CLIPBOARD_TEXT;
const MAX_IMAGE = PROTOCOL.FILE.MAX_CLIPBOARD_IMAGE;

let changecount = null;
try {
  changecount = require('./native/changecount');
} catch (err) {
  console.warn('[clipboard] native change counter unavailable, using content polling:', err && err.message);
}

/*
 * Windows "do not monitor" conventions (honoured by Windows' own clipboard history): password
 * managers add these registered formats so clipboard monitors skip the item.
 *   ExcludeClipboardContentFromMonitorProcessing  (any data)  → skip
 *   Clipboard Viewer Ignore                      (any data)  → skip
 *   CanIncludeInClipboardHistory                 DWORD 0     → skip
 * Checked through user32 (IsClipboardFormatAvailable — no OpenClipboard needed for presence) via
 * koffi; when koffi is unavailable, through Electron's clipboard.has() with the documented raw
 * format form ('electron application/osclipboard;format="…"') and the bare name.
 */
const SKIP_FORMATS = ['ExcludeClipboardContentFromMonitorProcessing', 'Clipboard Viewer Ignore'];
const HISTORY_FORMAT = 'CanIncludeInClipboardHistory';
/*
 * macOS convention (nspasteboard.org, honoured by clipboard managers): 1Password, KeePassXC,
 * Bitwarden … mark secrets and throw-away items with these pasteboard types. Checked through
 * Electron's clipboard.has() with the raw-format form.
 */
const MAC_SKIP_TYPES = ['org.nspasteboard.ConcealedType', 'org.nspasteboard.TransientType', 'org.nspasteboard.AutoGeneratedType'];
const rawFormat = (name) => `electron application/osclipboard;format="${name}"`;

let winFormats; // undefined = not initialised; null = unavailable
function nativeWinFormats() {
  if (winFormats !== undefined) return winFormats;
  winFormats = null;
  if (process.platform !== 'win32') return null;
  try {
    const koffi = require('koffi');
    const user32 = koffi.load('user32.dll');
    const kernel32 = koffi.load('kernel32.dll');
    const RegisterClipboardFormatW = user32.func('__stdcall', 'RegisterClipboardFormatW', 'uint32_t', ['str16']);
    const IsClipboardFormatAvailable = user32.func('__stdcall', 'IsClipboardFormatAvailable', 'int', ['uint32_t']);
    const OpenClipboard = user32.func('__stdcall', 'OpenClipboard', 'int', ['void *']);
    const CloseClipboard = user32.func('__stdcall', 'CloseClipboard', 'int', []);
    const GetClipboardData = user32.func('__stdcall', 'GetClipboardData', 'void *', ['uint32_t']);
    const GlobalLock = kernel32.func('__stdcall', 'GlobalLock', 'void *', ['void *']);
    const GlobalUnlock = kernel32.func('__stdcall', 'GlobalUnlock', 'int', ['void *']);
    const GlobalSize = kernel32.func('__stdcall', 'GlobalSize', 'size_t', ['void *']);
    const ids = new Map();
    const id = (name) => {
      if (!ids.has(name)) ids.set(name, RegisterClipboardFormatW(name) >>> 0); // atom; 0 = failure
      return ids.get(name);
    };
    const has = (name) => { const f = id(name); return f !== 0 && IsClipboardFormatAvailable(f) !== 0; };
    /** DWORD payload of a registered format, or null when it cannot be read. */
    const readDword = (name) => {
      const f = id(name);
      if (!f || !OpenClipboard(null)) return null;
      try {
        const h = GetClipboardData(f);
        if (!h) return null;
        if (Number(GlobalSize(h)) < 4) return null;
        const p = GlobalLock(h);
        if (!p) return null;
        try { return koffi.decode(p, 'uint32_t') >>> 0; } finally { GlobalUnlock(h); }
      } finally {
        CloseClipboard();
      }
    };
    winFormats = { has, readDword };
  } catch (err) {
    console.warn('[clipboard] native clipboard format checks unavailable:', err && err.message);
  }
  return winFormats;
}

function readCount() {
  if (!changecount || typeof changecount.get !== 'function') return null;
  try {
    const n = changecount.get();
    return typeof n === 'number' && Number.isFinite(n) ? n : null;
  } catch {
    return null;
  }
}

const sha = (data) => crypto.createHash('sha256').update(data).digest('hex');

function isPng(buf) {
  return !!buf && buf.length > PNG_MAGIC.length && buf.subarray(0, 8).equals(PNG_MAGIC);
}

function toBuffer(data) {
  if (Buffer.isBuffer(data)) return data;
  if (ArrayBuffer.isView(data)) return Buffer.from(data.buffer, data.byteOffset, data.byteLength);
  if (data instanceof ArrayBuffer) return Buffer.from(data);
  return null;
}

class ClipboardWatcher extends EventEmitter {
  /**
   * @param {{clipboard?:object, ClipboardItem?:Function, platform?:string,
   *          formats?:{has(name):boolean, readDword(name):number|null}|null,
   *          readCount?:()=>number|null}} [deps] injectable for tests
   *   (formats: Windows registered-format probe; null = unavailable → Electron clipboard.has fallback;
   *    readCount: clipboard change counter, null = unavailable; default native/changecount)
   */
  constructor(deps = {}) {
    super();
    this._deps = deps;
    this._subs = new Map();     // webContents.id → { wc, canReceive }
    this._timer = null;
    this._explicit = false;
    this._busy = false;
    this._lastCount = null;
    this._lastSig = null;
    this._suppress = null;      // { kind, sig, until }
  }

  get _cb() { return this._deps.clipboard || require('electron').clipboard; }
  get _Item() { return this._deps.ClipboardItem || require('electron').ClipboardItem; }

  /** Clipboard change counter, or null when unavailable. Never throws. */
  _count() {
    if (typeof this._deps.readCount !== 'function') return readCount();
    try {
      const n = this._deps.readCount();
      return typeof n === 'number' && Number.isFinite(n) ? n : null;
    } catch {
      return null;
    }
  }

  get running() { return !!this._timer; }

  /* ---------------------------------------------------------------- subscriptions */

  /**
   * Deliver 'clipboard:changed' to this webContents while subscribed.
   * @param {Electron.WebContents} wc
   * @param {{canReceive?:()=>boolean}} [opts] evaluated on every change (panel: permissions.clipboard)
   */
  subscribe(wc, opts = {}) {
    if (!wc || wc.isDestroyed()) return;
    const id = wc.id;
    if (!this._subs.has(id)) {
      wc.once('destroyed', () => this._unsubscribeId(id));
    }
    this._subs.set(id, { wc, canReceive: typeof opts.canReceive === 'function' ? opts.canReceive : () => true });
    this._ensurePolling();
  }

  unsubscribe(wc) {
    if (!wc) return;
    let id;
    try { id = wc.id; } catch { return; }
    this._unsubscribeId(id);
  }

  _unsubscribeId(id) {
    if (this._subs.delete(id)) this._ensurePolling();
  }

  isSubscribed(wc) {
    try { return this._subs.has(wc.id); } catch { return false; }
  }

  /** Explicitly keep polling regardless of subscribers (contract API). */
  start() { this._explicit = true; this._ensurePolling(); }
  stop() { this._explicit = false; this._ensurePolling(); }

  /** Stop everything (app quit). */
  dispose() {
    this._explicit = false;
    this._subs.clear();
    this._ensurePolling();
  }

  _ensurePolling() {
    const want = this._explicit || this._subs.size > 0;
    if (want && !this._timer) {
      this._timer = setInterval(() => this._tick(), POLL_MS);
      if (this._timer.unref) this._timer.unref();
      this._baseline();
    } else if (!want && this._timer) {
      clearInterval(this._timer);
      this._timer = null;
    }
  }

  /** Record the current clipboard state without emitting (starting sync never pushes old content). */
  async _baseline() {
    this._lastCount = this._count();
    if (this._lastCount !== null) return;
    try {
      const cur = await this._read();
      this._lastSig = cur && cur.kind !== 'unstable' ? cur.sig : null;
    } catch { /* ignore */ }
  }

  /* ---------------------------------------------------------------- polling */

  async _tick() {
    if (this._busy) return;
    this._busy = true;
    let count = null;
    try {
      count = this._count();
      if (count !== null && count === this._lastCount) return;
      const cur = await this._read(count);
      // Changed while it was being read: keep the old baselines so the next tick re-reads it.
      if (cur && cur.kind === 'unstable') return;
      if (count !== null) this._lastCount = count;
      if (!cur || cur.sig === this._lastSig) return;
      this._lastSig = cur.sig;
      if (this._isEcho(cur)) return;
      // Skipped, not retried: _lastCount/_lastSig already moved past this item.
      if (cur.kind === 'too-large' || cur.kind === 'excluded') return;
      this._deliver(cur.kind === 'text' ? { kind: 'text', text: cur.text } : { kind: 'image', png: cur.png });
    } catch (err) {
      if (count !== null) this._lastCount = count; // do not retry a failing read every 500 ms
      console.warn('[clipboard] poll failed:', err && err.message);
    } finally {
      this._busy = false;
    }
  }

  _isEcho(cur) {
    const s = this._suppress;
    if (!s || Date.now() > s.until) return false;
    // Images may be re-encoded by the OS between our write and the read-back, so a recent image
    // write suppresses the next image change by kind; text must match exactly.
    if (s.kind === 'image' ? cur.kind === 'image' : cur.sig === s.sig) {
      this._suppress = null;
      return true;
    }
    return false;
  }

  _deliver(item) {
    this.emit('change', item);
    const payload = item.kind === 'text'
      ? { kind: 'text', text: item.text }
      : { kind: 'image', png: new Uint8Array(item.png.buffer, item.png.byteOffset, item.png.byteLength) };
    for (const [id, sub] of this._subs) {
      try {
        if (sub.wc.isDestroyed()) { this._subs.delete(id); continue; }
        if (!sub.canReceive()) continue;
        sub.wc.send('clipboard:changed', payload);
      } catch (err) {
        console.warn('[clipboard] delivery failed:', err && err.message);
      }
    }
    this._ensurePolling();
  }

  /**
   * True when the current clipboard item asks clipboard monitors to skip it (password managers
   * etc.: Windows SKIP_FORMATS / HISTORY_FORMAT, macOS MAC_SKIP_TYPES above). Never throws.
   */
  async _excluded() {
    const platform = this._deps.platform || process.platform;
    if (platform === 'darwin') {
      for (const t of MAC_SKIP_TYPES) {
        try {
          if (await this._cb.has(rawFormat(t))) return true;
        } catch { /* this probe failed; the other types are still checked */ }
      }
      return false;
    }
    if (platform !== 'win32') return false;
    try {
      const nat = this._deps.formats !== undefined ? this._deps.formats : nativeWinFormats();
      if (nat) {
        if (SKIP_FORMATS.some((n) => nat.has(n))) return true;
        if (nat.has(HISTORY_FORMAT)) {
          const v = nat.readDword(HISTORY_FORMAT);
          return v === null || v === 0; // unreadable → treat as private
        }
        return false;
      }
      const has = async (name) => {
        for (const f of [rawFormat(name), name]) {
          try { if (await this._cb.has(f)) return true; } catch { /* that form is unsupported */ }
        }
        return false;
      };
      for (const n of SKIP_FORMATS) if (await has(n)) return true;
      // The DWORD value cannot be read through Electron's API: present → treat as private.
      return await has(HISTORY_FORMAT);
    } catch (err) {
      console.warn('[clipboard] exclusion check failed:', err && err.message);
      return false;
    }
  }

  /**
   * Read the clipboard. Text is preferred over images when both are present. Items marked
   * "do not monitor" come back as {kind:'excluded'} (with their own signature, never delivered).
   * The probe + read are bracketed by the change counter (count0 = its value before the probe):
   * {kind:'unstable'} = the clipboard changed in between, nothing about it can be trusted.
   * @param {number|null} [count0]
   * @returns {Promise<null | {kind:'text', text, sig} | {kind:'image', png, sig} | {kind:'too-large', sig}
   *                   | {kind:'excluded', sig} | {kind:'unstable'}>}
   */
  async _read(count0 = this._count()) {
    let excluded = await this._excluded();
    const cur = await this._readContent();
    const count1 = this._count();
    if (count0 !== null && count1 !== null) {
      if (count0 !== count1) return { kind: 'unstable' };
    } else if (cur && !excluded) {
      // No counter to prove the probe and the read saw the same item: probe again.
      excluded = await this._excluded();
    }
    if (!cur || !excluded) return cur;
    return { kind: 'excluded', sig: `x:${cur.sig}` };
  }

  async _readContent() {
    const items = await this._cb.read();
    if (!Array.isArray(items) || !items.length) return null;
    let textItem = null;
    let imageItem = null;
    for (const it of items) {
      const types = (it && Array.isArray(it.types)) ? it.types : [];
      if (!textItem && types.includes('text/plain')) textItem = it;
      if (!imageItem && types.includes('image/png')) imageItem = it;
    }
    if (textItem) {
      const blob = await textItem.getType('text/plain');
      const text = typeof blob === 'string' ? blob : (blob && typeof blob.text === 'function' ? await blob.text() : '');
      if (text) {
        if (text.length > MAX_TEXT) return { kind: 'too-large', sig: `T:${text.length}:${sha(text.slice(0, 4096))}` };
        return { kind: 'text', text, sig: `t:${sha(text)}` };
      }
    }
    if (imageItem) {
      const blob = await imageItem.getType('image/png');
      if (!blob || typeof blob.arrayBuffer !== 'function') return null;
      if (blob.size > MAX_IMAGE) return { kind: 'too-large', sig: `I:${blob.size}` };
      const png = Buffer.from(await blob.arrayBuffer());
      if (!isPng(png)) return null;
      return { kind: 'image', png, sig: `i:${sha(png)}` };
    }
    return null;
  }

  /* ---------------------------------------------------------------- writing */

  /**
   * Write remote clipboard content locally and suppress its echo.
   * @returns {Promise<{ok:boolean, reason?:string}>}
   */
  async write(item) {
    if (!item || typeof item !== 'object') return { ok: false, reason: 'bad-request' };
    try {
      if (item.kind === 'text') {
        if (typeof item.text !== 'string' || item.text.length > MAX_TEXT) return { ok: false, reason: 'bad-request' };
        const sig = `t:${sha(item.text)}`;
        this._suppress = { kind: 'text', sig, until: Date.now() + SUPPRESS_MS };
        await this._cb.writeText(item.text);
        this._afterWrite(sig);
        return { ok: true };
      }
      if (item.kind === 'image') {
        const png = toBuffer(item.png);
        if (!png || png.length > MAX_IMAGE || !isPng(png)) return { ok: false, reason: 'bad-request' };
        const sig = `i:${sha(png)}`;
        this._suppress = { kind: 'image', sig, until: Date.now() + SUPPRESS_MS };
        const Item = this._Item;
        const blob = new Blob([png], { type: 'image/png' });
        await this._cb.write([new Item({ 'image/png': blob })]);
        this._afterWrite(sig);
        return { ok: true };
      }
      return { ok: false, reason: 'bad-request' };
    } catch (err) {
      console.error('[clipboard] write failed:', err && err.message);
      return { ok: false, reason: 'write-failed' };
    }
  }

  _afterWrite(sig) {
    // Move the baselines past our own write so the next poll does not report it as a change.
    const count = this._count();
    if (count !== null) this._lastCount = count;
    this._lastSig = sig;
  }
}

const instance = new ClipboardWatcher();
module.exports = instance;
module.exports.ClipboardWatcher = ClipboardWatcher;
module.exports.isPng = isPng;
